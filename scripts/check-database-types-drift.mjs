#!/usr/bin/env node
// scripts/check-database-types-drift.mjs
// ============================================================
// Forward-guard for #4326: frontend/src/types/database.types.ts (the
// generated Supabase TS types, used by frontend code for compile-time
// column/table checks) and database/schema-snapshot.json (the committed
// mirror of prod's public schema used by the schema-column-guard,
// #3586/#4142) are two independent, manually-refreshed mirrors of the same
// live schema. Nothing keeps them in sync with each other.
//
// Evidence (30/8): the issue's own title (46 of 143 tables covered) was
// already stale — database.types.ts was regenerated 27/8 (commit e7c972de0,
// PR #4334) and now covers ~202 tables/views. But schema-snapshot.json
// (generatedAt 2026-08-25) and database.types.ts had already drifted apart
// again within days: relations present in one but not the other.
//
// This script is a WARN, not a FAIL, for the same reason #4142's sibling
// guard (check-schema-snapshot-staleness.mjs) is advisory: refreshing
// database.types.ts requires `npm run types:gen` (frontend/package.json),
// which needs a live Supabase project-id/session, and refreshing the
// snapshot requires prod DB access via infisical. Neither is available to
// CI/preflight, and this check must not block a PR that has nothing to do
// with the schema.
//
// Method: compare the top-level relation keys of database/schema-snapshot.json
// (`relations`) against the top-level keys of the `Tables` and `Views` blocks
// in database.types.ts (Database.public.Tables / Database.public.Views).
// Parsing is a plain indentation-based scan (this file is generated by the
// Supabase CLI with a stable 2-space-per-level layout), not a TS/AST parse —
// good enough for a name-drift check, not for verifying column shape.
//
// Note on backup_* relations: database/ has ~53 `backup_*_*` relations from
// past incident cleanups (tracked separately in #4333, paused pending owner
// input on whether to drop them from the snapshot). This script does NOT
// filter them out — see #4333 for that decision — but groups them in the
// report so the signal for genuinely new/removed tables isn't buried under
// ~50 backup-table lines.
//
// Usage:
//   node scripts/check-database-types-drift.mjs
//
// Exit code is always 0 (advisory) — same contract as
// check-schema-snapshot-staleness.mjs (#4142).

import { readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const snapshotPath = join(root, 'database', 'schema-snapshot.json');
const typesPath = join(root, 'frontend', 'src', 'types', 'database.types.ts');

const REFRESH_CMD = 'npm run types:gen   (koeres i frontend/, kraever et Supabase-projekt-login)';
const BACKUP_PREFIX = /^backup_/;

/**
 * Extract the top-level keys of one section ("Tables" or "Views") inside the
 * `public` block of a Supabase-generated database.types.ts file.
 *
 * Assumes the Supabase CLI's stable output layout: a `    <Section>: {` line
 * at 4-space indent, followed by `      <key>: {` lines at 6-space indent
 * for each relation, until the next 4-space-indent section line.
 *
 * @param {string} source
 * @param {string} sectionName
 * @returns {string[] | null} null if the section header was not found
 */
export function extractTypeSectionKeys(source, sectionName) {
  const lines = source.split('\n').map((l) => l.replace(/\r$/, ''));
  const sectionStart = lines.findIndex((l) => l === `    ${sectionName}: {`);
  if (sectionStart === -1) return null;

  const keys = [];
  const keyRe = /^      (\w+): \{$/;
  for (let i = sectionStart + 1; i < lines.length; i++) {
    const line = lines[i];
    // Next section at the same (4-space) indent level ends this one.
    if (/^    \w+: \{$/.test(line)) break;
    if (/^    \}$/.test(line)) break; // end of `public: { ... }`
    const m = line.match(keyRe);
    if (m) keys.push(m[1]);
  }
  return keys;
}

function groupBackup(keys) {
  const backup = keys.filter((k) => BACKUP_PREFIX.test(k)).sort();
  const rest = keys.filter((k) => !BACKUP_PREFIX.test(k)).sort();
  return { backup, rest };
}

function main() {
  let snapshot;
  try {
    snapshot = JSON.parse(readFileSync(snapshotPath, 'utf8'));
  } catch (err) {
    console.warn(`WARN database-types-drift: kunne ikke laese ${snapshotPath} (${err.message}) — springer tjek over.`);
    return;
  }

  const snapshotKeys = new Set(Object.keys(snapshot.relations ?? {}));
  if (snapshotKeys.size === 0) {
    console.warn('WARN database-types-drift: schema-snapshot.json har ingen "relations" — springer tjek over.');
    return;
  }

  let typesSource;
  try {
    typesSource = readFileSync(typesPath, 'utf8');
  } catch (err) {
    console.warn(`WARN database-types-drift: kunne ikke laese ${typesPath} (${err.message}) — springer tjek over.`);
    return;
  }

  const tableKeys = extractTypeSectionKeys(typesSource, 'Tables');
  const viewKeys = extractTypeSectionKeys(typesSource, 'Views');
  if (tableKeys === null || viewKeys === null) {
    console.warn(`WARN database-types-drift: kunne ikke finde "Tables"/"Views"-blokken i ${typesPath} (layout aendret?) — springer tjek over.`);
    return;
  }

  const typesKeys = new Set([...tableKeys, ...viewKeys]);

  const onlyInSnapshot = [...snapshotKeys].filter((k) => !typesKeys.has(k));
  const onlyInTypes = [...typesKeys].filter((k) => !snapshotKeys.has(k));

  if (onlyInSnapshot.length === 0 && onlyInTypes.length === 0) {
    console.log(
      `database-types-drift: OK — ${snapshotKeys.size} relationer i schema-snapshot.json matcher `
      + `${typesKeys.size} Tables/Views-noegler i database.types.ts.`,
    );
    return;
  }

  console.warn('');
  console.warn(
    `WARN database-types-drift (#4326): schema-snapshot.json (${snapshotKeys.size} relationer) og `
    + `database.types.ts (${typesKeys.size} Tables/Views) er ikke i sync.`,
  );
  console.warn(`  schema-snapshot.json generatedAt: ${snapshot.generatedAt ?? '(mangler)'}`);

  if (onlyInSnapshot.length > 0) {
    const { backup, rest } = groupBackup(onlyInSnapshot);
    console.warn(`  Kun i schema-snapshot.json (${onlyInSnapshot.length}):`);
    for (const name of rest) console.warn(`    - ${name}`);
    if (backup.length > 0) {
      console.warn(`    - (+ ${backup.length} backup_*-relationer, se #4333 — paused, ejer-input mangler, IKKE filtreret her)`);
    }
  }

  if (onlyInTypes.length > 0) {
    const { backup, rest } = groupBackup(onlyInTypes);
    console.warn(`  Kun i database.types.ts (${onlyInTypes.length}):`);
    for (const name of rest) console.warn(`    - ${name}`);
    if (backup.length > 0) {
      console.warn(`    - (+ ${backup.length} backup_*-relationer, se #4333 — paused, ejer-input mangler, IKKE filtreret her)`);
    }
  }

  console.warn('  De to filer er uafhaengige, manuelt-genererede spejle af samme live schema, og driver');
  console.warn('  stille fra hinanden imellem refreshes (samme klasse som #4142).');
  console.warn(`  Refresh database.types.ts: ${REFRESH_CMD}`);
  console.warn('  Refresh schema-snapshot.json: infisical run --env=prod -- node scripts/lint-schema-columns.mjs --update-snapshot');
  console.warn('');
}

main();
